import assert from 'node:assert/strict';
import { writeFileSync } from 'node:fs';
import { BUSINESS_TYPES, createMarketDemo, defaultFilters, exportCsv, percent, rate, selectMarket, sum } from '../../../lib/market-demo/model';

let checks = 0;
const check = (value: unknown) => { assert.ok(value); checks++; };
const units = ['SAS170 PMC板块', 'SAS610 咨询板块', 'SAS680 数字技术板块'];
const demo = createMarketDemo(units), filters = defaultFilters('全部板块', '2026-11-10');
const all = selectMarket(demo, filters);
check(JSON.stringify(demo) === JSON.stringify(createMarketDemo(units)));
check(all.opportunities.length === units.length * 3 * 12 * 2);
check(demo.opportunities.every(row => row.name.startsWith('模拟') && row.customer.startsWith('模拟')));
check(demo.opportunities.every(row => row.estimated >= row.bid && row.bid >= row.weighted && row.weighted >= 0));
check(all.signed === sum(all.actual, row => row.amount));
check(all.weighted === sum(all.opportunities, row => row.weighted));
check(sum(BUSINESS_TYPES, type => sum(all.actual.filter(row => row.type === type), row => row.amount)) === all.signed);
check(sum(units, unit => sum(all.actual.filter(row => row.unit === unit), row => row.amount)) === all.signed);
check(sum(Array.from({ length: 12 }, (_, i) => i + 1), month => sum(all.contracts.filter(row => Number(row.date.slice(5, 7)) === month), row => row.amount)) === sum(all.contracts, row => row.amount));
check(all.actual.every(row => row.date <= '2026-11-10'));
check(all.frameworks.every(row => row.date <= '2026-11-10'));
const one = selectMarket(demo, { ...filters, unit: units[0], types: ['EPC'] });
check(one.opportunities.every(row => row.unit === units[0] && row.type === 'EPC'));
check(one.actual.every(row => row.unit === units[0] && row.type === 'EPC'));
check(one.targets.length === 1);
const stage = { ...filters, stage: '已签约' };
check(selectMarket(demo, stage, true).opportunities.every(row => row.stage === '已签约'));
check(selectMarket(demo, stage).opportunities.length === all.opportunities.length);
const dates = selectMarket(demo, { ...filters, application: ['2026-02-01', '2026-02-28'], bidTime: ['2026-02-10', '2026-02-15'], bidDate: ['2026-02-16', '2026-02-20'] });
check(dates.opportunities.length === units.length * 3 * 2);
check(dates.opportunities.every(row => row.applicationDate.startsWith('2026-02')));
check(selectMarket(demo, { ...filters, application: ['2026-02-03', '2026-02-04'] }).opportunities.length === 0);
const empty = selectMarket(demo, { ...filters, types: [] });
check(empty.opportunities.length === 0 && empty.contracts.length === 0 && empty.frameworks.length === 0 && empty.target === 0);
check(percent(rate(0, 0)) === '—' && percent(rate(10, 0)) === '—' && percent(rate(5, 10)) === '50.00%');
const bands = [[0, 50], [50, 200], [200, 500], [500, Infinity]];
check(sum(bands, ([min, max]) => sum(all.actual.filter(row => row.amount >= min && row.amount < max), row => row.amount)) === all.signed);
const csv = exportCsv(one.contracts);
check(csv.charCodeAt(0) === 0xfeff && csv.split('\r\n').length === one.contracts.length + 1);
check(exportCsv([{ ...one.contracts[0], name: '模拟"项目,测试' }]).includes('"模拟""项目,测试"'));
const result = { verdict: 'PASS', checks, syntheticOpportunityCount: demo.opportunities.length, financialUnit: '万元' };
writeFileSync('docs/evidence/2026-11-10-ops-market-demo/model-results.json', JSON.stringify(result, null, 2));
console.log(JSON.stringify(result));
