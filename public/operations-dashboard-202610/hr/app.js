import {createLifecycle} from '../shared/lifecycle.js';
import {attachHostBridge} from '../shared/host-bridge.js';
import {register as register0} from './model.js';
import {register as register1} from './components.js';
import {register as register2} from './sections.js';
import {register as register3} from './charts.js';
import {register as register4} from './dialogs.js';
import {register as register5} from './exports.js';
import {register as register6} from './theme.js';
import * as data from './data.js';
export function mount() {
 const ctx={lifecycle:createLifecycle()};
 register0(ctx);
 register1(ctx);
 register2(ctx);
 register3(ctx);
 register4(ctx);
 register5(ctx);
 register6(ctx);
 ctx.lifecycle.onDispose(()=>Object.values(ctx.charts||{}).forEach(chart=>{if(chart?.destroy)chart.destroy();else chart?.dispose?.();}));
ctx.S=window.HR_SOURCE_SNAPSHOT;
ctx.$=id => document.getElementById(id);
ctx.escape=value => String(value ?? '—').replace(/[&<>"']/g, c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
ctx.fmt=(value, decimals = 0) => value == null || !Number.isFinite(Number(value)) ? '—' : Number(value).toLocaleString('zh-CN', {minimumFractionDigits:decimals,maximumFractionDigits:decimals});
ctx.pct=value => value == null ? '—' : ctx.fmt(value, 2) + '%';
if (!ctx.S) { ctx.$('hrSourceNote').textContent = '来源快照加载失败，请刷新页面重试。'; document.body.dataset.ready = 'error'; return; }
ctx.THEMES=data.THEMES;
ctx.state={theme:'blue',unit:'全部板块',type:'PMC',mapZoom:1};
ctx.charts={};
ctx.chinaReady=false;
ctx.pendingResize=false;
ctx.dialogHistory=[];
ctx.lastTrigger=null;
ctx.scrollLock=null;
ctx.theme=() => ctx.THEMES[ctx.state.theme];
ctx.unitInfo=() => (ctx.S.units || []).find(u => ctx.state.unit === u.code + ' ' + u.name || ctx.state.unit === u.name);
ctx.unitLabel=() => ctx.unitInfo() ? ctx.unitInfo().code + ' ' + ctx.unitInfo().name : '全部板块';
ctx.scopeNote=global => ctx.state.unit === '全部板块' ? '全公司快照' : global ? '来源未提供组织分解，保留全公司快照' : '仅展示明确归属 ' + ctx.unitLabel() + ' 的来源记录';
ctx.textEmpty=message => '<div class="empty">' + ctx.escape(message) + '</div>';
ctx.safeHtml=html => ({html});
ctx.COORDS=data.COORDS;
ctx.lifecycle.listen(ctx.$('hrDialog'),'close',()=>{ctx.disposeDialogCharts();ctx.dialogHistory=[];if(ctx.scrollLock){document.documentElement.style.overflow=ctx.scrollLock.html;document.documentElement.style.overscrollBehavior=ctx.scrollLock.overscroll;document.body.style.overflow=ctx.scrollLock.body;scrollTo(ctx.scrollLock.x,ctx.scrollLock.y);ctx.scrollLock=null;}ctx.lastTrigger?.focus?.({preventScroll:true});ctx.lastTrigger=null;});
ctx.lifecycle.listen(ctx.$('closeHrDialog'),'click',ctx.closeModal);
ctx.lifecycle.listen(ctx.$('closeHrDialogFooter'),'click',ctx.closeModal);
ctx.lifecycle.listen(ctx.$('hrDialogBack'),'click',()=>{if(ctx.dialogHistory.length>1){ctx.dialogHistory.pop();ctx.drawModal();}});
ctx.OFFICE_DIMS=data.OFFICE_DIMS;
ctx.DEMAND_DIMS=data.DEMAND_DIMS;
document.querySelectorAll('[data-type]').forEach(button=>ctx.lifecycle.listen(button,'click',()=>{ctx.state.type=button.dataset.type;ctx.renderProjects();}));
document.querySelectorAll('[data-hr-detail-kind]').forEach(button=>ctx.lifecycle.listen(button,'click',()=>ctx.openKpi(button.dataset.hrDetailKind,button)));
ctx.lifecycle.listen(ctx.$('openMapFullscreen'),'click',event=>ctx.openMapFullscreen(event.currentTarget));
ctx.lifecycle.listen(ctx.$('openPersonnelSearch'),'click',event=>ctx.openSearch(event.currentTarget));
ctx.lifecycle.listen(ctx.$('openDemandPivot'),'click',event=>ctx.openPivot('demand',event.currentTarget));
ctx.lifecycle.listen(ctx.$('openOfficePivot'),'click',event=>ctx.openPivot('office',event.currentTarget));
document.querySelectorAll('[data-map-zoom]').forEach(button=>ctx.lifecycle.listen(button,'click',()=>{ctx.state.mapZoom=Math.max(.6,Math.min(6,ctx.state.mapZoom*(button.dataset.mapZoom==='in'?1.25:.8)));ctx.$('mapZoom').textContent=ctx.fmt(ctx.state.mapZoom*100)+'%';ctx.renderMap();}));
ctx.lifecycle.listen(ctx.$('resetMap'),'click',()=>{ctx.state.mapZoom=1;ctx.$('mapZoom').textContent='100%';ctx.renderMap();});
attachHostBridge({onTheme:ctx.applyTheme,onFilter:ctx.applyFilter,onResize:ctx.resizeCharts},ctx.lifecycle,true);
ctx.lifecycle.observe(ctx.resizeCharts).observe(ctx.$('hrPage'));
ctx.lifecycle.listen(window,'resize',ctx.resizeCharts);
window.hrDashboard={get state(){return{...ctx.state};},get source(){return ctx.S;},charts:ctx.charts};
ctx.applyTheme('blue');
ctx.render();
document.body.dataset.ready='true';
ctx.lifecycle.fetch('/geo/china.json').then(response=>{if(!response.ok)throw new Error('地图资源不可用');return response.json();}).then(geo=>{if(ctx.lifecycle.disposed)return;echarts.registerMap('hrChina',geo);ctx.chinaReady=true;ctx.$('mapStatus').textContent='';ctx.renderMap();if(ctx.$('dialogDispatchMap'))ctx.renderMap('dialogDispatchMap');}).catch(()=>{if(ctx.lifecycle.disposed)return;ctx.$('mapStatus').textContent='地图资源加载失败。派遣区域汇总和项目明细仍可查看，请刷新重试。';});
 return {update(context){if(ctx.lifecycle.disposed)return;if(ctx.applyHostTheme)ctx.applyHostTheme(context.theme);else ctx.applyTheme(context.theme);if(ctx.applyHostFilter)ctx.applyHostFilter(context);else ctx.applyFilter(context);},destroy:()=>ctx.lifecycle.dispose(),get disposed(){return ctx.lifecycle.disposed;}};
}
window.__boardRuntime?.destroy();
window.__boardRuntime=mount();
