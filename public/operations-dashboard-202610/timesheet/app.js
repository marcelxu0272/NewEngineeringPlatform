import {createLifecycle} from '../shared/lifecycle.js';
import {attachHostBridge} from '../shared/host-bridge.js';
import {register as register0} from './model.js';
import {register as register1} from './charts.js';
import {register as register2} from './sections.js';
import {register as register3} from './layout.js';
import {register as register4} from './theme.js';
import {register as register5} from './dialogs.js';
import {register as register6} from './exports.js';
import * as data from './data.js';
export function mount() {
 const ctx={lifecycle:createLifecycle()};
 register0(ctx);
 register1(ctx);
 register2(ctx);
 register3(ctx);
 register4(ctx);
 register5(ctx);
 register6(ctx);
 ctx.lifecycle.onDispose(()=>Object.values(ctx.charts||{}).forEach(chart=>{if(chart?.destroy)chart.destroy();else chart?.dispose?.();}));
ctx.THEMES=data.THEMES;
ctx.MONTHS=data.MONTHS;
ctx.HISTORY_MONTHS=data.HISTORY_MONTHS;
ctx.UNIT_CONFIGS=data.UNIT_CONFIGS;
ctx.DEFAULT_UNIT=data.DEFAULT_UNIT;
ctx.round=value => Math.round((value + Number.EPSILON) * 100) / 100;
ctx.sum=values => ctx.round(values.reduce((total,value) => total + (value || 0),0));
ctx.rate=(hours,capacity) => hours == null || capacity == null || capacity <= 0 ? null : ctx.round(hours / capacity * 100);
ctx.number=value => value == null || !Number.isFinite(value) ? '—' : value.toLocaleString('zh-CN',{minimumFractionDigits:2,maximumFractionDigits:2});
ctx.percentage=value => value == null || !Number.isFinite(value) ? '—' : ctx.number(value) + '%';
ctx.monthLabel=month => {const [year,m] = month.split('-'); return year + '年' + Number(m) + '月';};
ctx.escapeHtml=value => String(value).replace(/[&<>"']/g,c => ({'&':'&amp;','<':'&lt;','>':'&gt;','"':'&quot;',"'":'&#39;'}[c]));
ctx.MODELS=new Map(ctx.UNIT_CONFIGS.map(config=>[config.unit,ctx.createModel(config)]));
ctx.state={unit:'全部板块',effectiveUnit:ctx.DEFAULT_UNIT,theme:'blue',month:ctx.MONTHS[0],trendMode:'history',sort:'desc',query:''};
ctx.model=ctx.MODELS.get(ctx.DEFAULT_UNIT);
ctx.lastDetailTrigger=null;
ctx.scrollLock=null;
ctx.charts={};
ctx.$=id => document.getElementById(id);
ctx.theme=() => ctx.THEMES[ctx.state.theme];
ctx.axisMax=values => Math.ceil(Math.max(100,...values.filter(v=>v!=null))/25)*25 + 25;
ctx.lifecycle.listen(ctx.$('detailDialog'),'close',()=>{
    if(ctx.scrollLock){document.documentElement.style.overflow=ctx.scrollLock.rootOverflow;document.documentElement.style.overscrollBehavior=ctx.scrollLock.rootOverscroll;document.body.style.overflow=ctx.scrollLock.bodyOverflow;window.scrollTo(ctx.scrollLock.x,ctx.scrollLock.y);ctx.scrollLock=null;}
    if(ctx.lastDetailTrigger)ctx.lastDetailTrigger.focus({preventScroll:true});ctx.lastDetailTrigger=null;
  });
ctx.lifecycle.listen(ctx.$('closeDetail'),'click',ctx.closeDetail);
ctx.lifecycle.listen(ctx.$('detailDialog'),'click',event=>{if(event.target===ctx.$('detailDialog')){const r=ctx.$('detailDialog').getBoundingClientRect();if(event.clientX<r.left||event.clientX>r.right||event.clientY<r.top||event.clientY>r.bottom)ctx.closeDetail();}});
document.querySelectorAll('[data-detail-kind]').forEach(button=>ctx.lifecycle.listen(button,'click',()=>ctx.openDetail(button.dataset.detailKind,button)));
document.querySelectorAll('[data-trend-mode]').forEach(button=>ctx.lifecycle.listen(button,'click',()=>{ctx.state.trendMode=button.dataset.trendMode;ctx.renderTrend();ctx.resizeCharts();}));
document.querySelectorAll('[data-forecast-month]').forEach(button=>ctx.lifecycle.listen(button,'click',()=>{ctx.state.month=button.dataset.forecastMonth;ctx.$('exportStatus').textContent='';ctx.renderForecast();ctx.resizeCharts();}));
ctx.lifecycle.listen(ctx.$('personnelSort'),'change',event=>{ctx.state.sort=event.target.value;ctx.renderForecast();ctx.resizeCharts();});
ctx.lifecycle.listen(ctx.$('personnelSearchForm'),'submit',event=>{event.preventDefault();ctx.state.query=ctx.$('personnelSearch').value.trim();ctx.$('exportStatus').textContent='';ctx.renderForecast();ctx.resizeCharts();});
ctx.lifecycle.listen(ctx.$('personnelSearch'),'search',()=>{if(!ctx.$('personnelSearch').value){ctx.state.query='';ctx.renderForecast();ctx.resizeCharts();}});
ctx.lifecycle.listen(ctx.$('exportSummary'),'click',()=>ctx.downloadCsv('summary'));
ctx.lifecycle.listen(ctx.$('exportDetails'),'click',()=>ctx.downloadCsv('details'));
attachHostBridge({onTheme:ctx.applyTheme,onFilter:ctx.applyFilter,onResize:ctx.resizeCharts},ctx.lifecycle,true);
ctx.lifecycle.observe(ctx.resizeCharts).observe(ctx.$('timesheetPage'));
ctx.lifecycle.listen(window,'resize',ctx.resizeCharts);
window.timesheetDashboard={get state(){return {...ctx.state};},get model(){return ctx.model;},charts:ctx.charts,getPersonnelRows:ctx.getPersonnelRows};
ctx.applyTheme('blue');
document.body.dataset.ready='true';
 return {update(context){if(ctx.lifecycle.disposed)return;if(ctx.applyHostTheme)ctx.applyHostTheme(context.theme);else ctx.applyTheme(context.theme);if(ctx.applyHostFilter)ctx.applyHostFilter(context);else ctx.applyFilter(context);},destroy:()=>ctx.lifecycle.dispose(),get disposed(){return ctx.lifecycle.disposed;}};
}
window.__boardRuntime?.destroy();
window.__boardRuntime=mount();
